"""Builds the run report from captured execution data only.

Hard rule: every number in the output is read from a trace file written by an
actual run. Nothing here is typed by hand, and anything absent from the traces
is printed as NOT CAPTURED rather than estimated.

This script exists because the previous project's verification document reported
latencies, token counts and metric values that did not match its own stored
records. The fix is structural: make the report a function of the artifacts.
"""

import glob
import json
import os
import statistics
import sys

TRACE_DIR = "traces"
OUT = "docs/run_report.md"


def val(d: dict, *path, default="NOT CAPTURED"):
    cur = d
    for k in path:
        if not isinstance(cur, dict) or k not in cur:
            return default
        cur = cur[k]
    return default if cur is None else cur


def main() -> int:
    paths = sorted(glob.glob(os.path.join(TRACE_DIR, "*.json")))
    if not paths:
        print(f"No traces in {TRACE_DIR}/. Run the pipeline first.", file=sys.stderr)
        return 1

    traces = [json.load(open(p)) for p in paths]
    lines = ["# Run Report", "",
             "Generated by `scripts/generate_run_report.py` from the files in `traces/`.",
             "Every value below was captured during a real run. Values absent from the",
             "traces are printed as NOT CAPTURED and are not estimated.", "",
             f"- Traces read: {len(traces)}",
             f"- Source files: {', '.join(os.path.basename(p) for p in paths)}", ""]

    lines += ["## Per deal", "",
              "| deal | band | score | agent turns | tool calls | tokens | latency (ms) | verified | warnings |",
              "|---|---|---|---|---|---|---|---|---|"]
    lat, tok = [], []
    for t in traces:
        agents = t.get("agents") or []
        turns = len(agents) if agents else "NOT CAPTURED"
        tools = sum(a.get("tool_call_count", 0) for a in agents) if agents else "NOT CAPTURED"
        tokens = sum(a.get("prompt_tokens", 0) + a.get("output_tokens", 0) for a in agents) if agents else 0
        latency = sum(a.get("latency_ms", 0) for a in agents) if agents else 0
        if agents:
            tok.append(tokens)
            lat.append(latency)
        ver = t.get("verification") or {}
        warns = sum(1 for f in ver.get("failures", []) if f.get("severity") == "WARNING")
        lines.append(
            f"| {val(t, 'deal_id')} | {val(t, 'deterministic', 'band')} | "
            f"{val(t, 'deterministic', 'risk_score')} | {turns} | {tools} | "
            f"{tokens or 'NOT CAPTURED'} | {latency:.0f} | {ver.get('passed', 'NOT CAPTURED')} | {warns} |")

    lines += ["", "## Aggregate", ""]
    if lat:
        lines += [f"- Latency p50: {statistics.median(lat):.0f} ms",
                  f"- Latency max: {max(lat):.0f} ms",
                  f"- Tokens per deal (mean): {statistics.mean(tok):.0f}",
                  f"- Sample size: {len(lat)} deals"]
    else:
        lines.append("- NOT CAPTURED (no agent telemetry in traces)")

    models = sorted({a.get("model", "NOT CAPTURED") for t in traces for a in (t.get("agents") or [])})
    lines += ["", f"- Models observed: {', '.join(models) if models else 'NOT CAPTURED'}",
              f"- Verification passed: {sum(1 for t in traces if val(t, 'verification', 'passed', default=False))}"
              f"/{len(traces)}", ""]

    lines += ["## Tool calls actually made", ""]
    for t in traces:
        names = [c.get("tool") for a in (t.get("agents") or []) for c in a.get("tool_calls", [])]
        lines.append(f"- {val(t, 'deal_id')}: {', '.join(names) if names else 'NOT CAPTURED'}")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {OUT} from {len(traces)} captured traces.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
